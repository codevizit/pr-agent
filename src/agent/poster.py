import hashlib
import re

from agent.annotate import HUNK_RE

RANK = {"low": 0, "medium": 1, "high": 2}
MARKER_RE = re.compile(r"<!-- pr-agent:fp=([0-9a-f]{12}) -->")


def _clean(text: str) -> str:
    """Neutralize @mentions and anything that could forge our hidden markers."""
    return text.replace("<!--", "").replace("-->", "").replace("@", "@\u200b")


def added_line_texts(patch: str) -> dict[int, str]:
    """Map new-file line number -> text for every added line in a patch."""
    texts: dict[int, str] = {}
    old_left = new_left = n_line = 0
    for line in patch.split("\n"):
        h = HUNK_RE.match(line)
        if h:
            old_left = 1 if h[2] is None else int(h[2])
            new_left = 1 if h[4] is None else int(h[4])
            n_line = int(h[3])
            continue
        if line.startswith("\\") or (old_left <= 0 and new_left <= 0):
            continue
        kind = line[:1]
        if kind == "+":
            new_left -= 1
            texts[n_line] = line[1:]
            n_line += 1
        elif kind == "-":
            old_left -= 1
        else:
            old_left -= 1
            new_left -= 1
            n_line += 1
    return texts


def fingerprint(path: str, category: str, line_text: str) -> str:
    norm = " ".join(line_text.split())
    return hashlib.sha256(f"{path}|{category}|{norm}".encode("utf-8")).hexdigest()[:12]


def comment_body(f: dict, fp: str) -> str:
    lines = [
        f"**{f['severity'].capitalize()} - {f['category']}:** {_clean(f['title'])}",
        "",
        _clean(f["explanation"]),
    ]
    if f.get("suggestion"):
        lines += ["", f"**Suggested fix:** {_clean(f['suggestion'])}"]
    lines += ["", f"<!-- pr-agent:fp={fp} -->"]
    return "\n".join(lines)


def summary_body(state: dict, stats: dict, cfg: dict) -> str:
    lines = [
        "### Automated review",
        "",
        f"Reviewed {len(state.get('kept_files', []))} file(s) and posted "
        f"{stats['posted']} inline comment(s).",
    ]
    if stats["over_limit"]:
        lines.append(
            f"- {stats['over_limit']} more finding(s) not posted "
            f"(limit: {cfg['max_comments']} comments per review)."
        )
    if stats["below_threshold"]:
        lines.append(
            f"- {stats['below_threshold']} finding(s) below the "
            f"{cfg['min_severity']} severity threshold not shown."
        )
    for s in state.get("skipped_files", []):
        lines.append(f"- Skipped `{_clean(s['path'])}`: {_clean(s['reason'])}")
    for note in state.get("notes", []):
        lines.append(f"- Note: {_clean(note)}")
    lines += ["", "_Generated by an AI model. Treat these as suggestions and verify before acting._"]
    return "\n".join(lines)


def plan_review(state: dict, existing_bodies: list[str], cfg: dict) -> dict:
    min_rank = RANK[cfg["min_severity"]]
    seen = {fp for body in existing_bodies for fp in MARKER_RE.findall(body)}
    texts = {f["path"]: added_line_texts(f["patch"]) for f in state.get("kept_files", [])}

    below = duplicates = 0
    candidates, batch = [], set()
    for f in state.get("findings", []):
        if RANK[f["severity"]] < min_rank:
            below += 1
            continue
        text = texts.get(f["path"], {}).get(f["line"], "")
        fp = fingerprint(f["path"], f["category"], text)
        if fp in seen or fp in batch:
            duplicates += 1
            continue
        batch.add(fp)
        candidates.append((f, fp))

    candidates.sort(key=lambda c: (-RANK[c[0]["severity"]], c[0]["path"], c[0]["line"]))
    chosen = candidates[: cfg["max_comments"]]
    stats = {
        "posted": len(chosen),
        "below_threshold": below,
        "duplicates": duplicates,
        "over_limit": len(candidates) - len(chosen),
    }
    if not chosen:
        return {"payload": None, "stats": stats}
    payload = {
        "body": summary_body(state, stats, cfg),
        "event": "COMMENT",
        "comments": [
            {"path": f["path"], "line": f["line"], "side": "RIGHT", "body": comment_body(f, fp)}
            for f, fp in chosen
        ],
    }
    return {"payload": payload, "stats": stats}